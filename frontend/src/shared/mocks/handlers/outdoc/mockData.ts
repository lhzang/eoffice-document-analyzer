export function genMockAdminDocTypeData(
  page: number,
  pageSize: number,
  unpaged: boolean
): PageDocumentBook {
  return {
    totalPages: Math.ceil(245 / pageSize),
    pageSize: pageSize,        
    pageNumber: page,          
    totalItems: 245,  
    content: unpaged
      ? Array.from({ length: 245 }).map((_, index) => ({
          id: index.toString(),
          name: 'Văn bản ne' + index,
          shortName: 'VB' + index
        }))
      : Array.from({ length: pageSize }).map((_, index) => ({
          id: ((page - 1) * pageSize + index).toString(),
          name: 'Văn bản ne' + ((page - 1) * pageSize + index),
          shortName: 'VB' + ((page - 1) * pageSize + index)
        }))
  }
}








